import json
import math  # Added for ceiling division
import os

import pandas as pd
from datasets import Dataset
from dotenv import load_dotenv
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_openai import AzureChatOpenAI
from ragas import evaluate
from ragas.metrics import (
    answer_correctness,
    answer_relevancy,
    context_precision,
    context_recall,
    faithfulness,
)

load_dotenv()


def validate_evaluation_data(data):
    """
    Validates and cleans the evaluation data, ensuring correct column names and formats.
    """
    cleaned_data = []
    skipped_count = 0

    # These are the column names generated by the previous script and expected by Ragas defaults.
    REQUIRED_COLS = {"question", "answer", "contexts", "ground_truth"}

    for i, item in enumerate(data):
        try:
            # Check for missing required columns
            if not REQUIRED_COLS.issubset(item.keys()):
                print(
                    f"Skipping item #{i}: Missing one of required keys {REQUIRED_COLS}"
                )
                skipped_count += 1
                continue

            # Ensure contexts is a non-empty list of non-empty strings
            contexts = item.get("contexts", [])
            if isinstance(contexts, str):
                contexts = [contexts]

            valid_contexts = [
                ctx for ctx in contexts if isinstance(ctx, str) and ctx.strip()
            ]

            if not valid_contexts:
                print(f"Skipping item #{i}: No valid contexts found.")
                skipped_count += 1
                continue

            # Ensure required fields are not empty
            if (
                not item.get("question")
                or not item.get("answer")
                or not item.get("ground_truth")
            ):
                print(
                    f"Skipping item #{i}: question, answer, or ground_truth is empty."
                )
                skipped_count += 1
                continue

            item["contexts"] = valid_contexts
            cleaned_data.append(item)

        except Exception as e:
            print(f"Error processing item #{i}: {e}")
            skipped_count += 1
            continue

    print(
        f"Validation complete. Original items: {len(data)}, Valid items: {len(cleaned_data)}, Skipped: {skipped_count}"
    )
    return cleaned_data


def main():
    """
    Main function to discover, evaluate, and summarize RAGAS datasets.
    """
    # --- 1. Setup Models ---
    print("Setting up evaluation models...")
    try:
        # Note: The embedding model used here should ideally match the one used for generation/indexing
        # for metrics like context_recall to be most accurate.
        embedding_model = HuggingFaceEmbeddings(
            model_name=os.getenv("EMBEDDING_MODEL"),
            model_kwargs={"device": "cuda"},
            cache_folder="./cache",
        )

        azure_llm_for_eval = AzureChatOpenAI(
            azure_deployment=os.getenv("AZURE_OPENAI_DEPLOYMENT", "IT108_gpt35"),
            openai_api_version=os.getenv(
                "AZURE_OPENAI_API_VERSION", "2023-07-01-preview"
            ),
            temperature=0.1,
            max_tokens=4096,
            request_timeout=120,  # Increased timeout for robustness
        )
    except Exception as e:
        print(f"Error initializing models: {e}")
        return

    # --- 2. Discover and Loop Through Datasets ---
    data_dir = "./data"
    files_to_evaluate = [
        f
        for f in os.listdir(data_dir)
        if f.startswith("ragas_eval_") and f.endswith(".json")
    ]

    if not files_to_evaluate:
        print(
            f"ERROR: No evaluation files found in '{data_dir}'. Please run the generation script first."
        )
        return

    all_results_summary = []

    # Define batch size
    BATCH_SIZE = 10

    for filename in files_to_evaluate:
        print(f"\n{'=' * 80}")
        print(f"🔥 Starting Evaluation for: {filename}")
        print(f"{'=' * 80}")

        file_path = os.path.join(data_dir, filename)

        try:
            # Load and validate the entire dataset first
            with open(file_path, "r", encoding="utf-8") as f:
                raw_data = json.load(f)

            evaluation_data = validate_evaluation_data(raw_data)
            if not evaluation_data:
                print("No valid data after validation. Skipping file.")
                continue

            # This list will store the DataFrames from each batch evaluation
            all_batch_results_df = []

            num_items = len(evaluation_data)
            num_batches = math.ceil(num_items / BATCH_SIZE)

            # --- Start Batch Processing Loop ---
            for i in range(0, num_items, BATCH_SIZE):
                batch_data = evaluation_data[i : i + BATCH_SIZE]
                batch_number = (i // BATCH_SIZE) + 1

                print(
                    f"\n--- Processing Batch {batch_number}/{num_batches} for {filename} ({len(batch_data)} items) ---"
                )

                # Convert the current batch to a Hugging Face Dataset
                ragas_dataset_batch = Dataset.from_list(batch_data)

                # Define metrics
                metrics = [
                    faithfulness,
                    answer_relevancy,
                    context_precision,
                    context_recall,
                    answer_correctness,
                ]

                # Execute RAGAS evaluation on the batch
                result_batch = evaluate(
                    dataset=ragas_dataset_batch,
                    metrics=metrics,
                    llm=azure_llm_for_eval,
                    embeddings=embedding_model,
                    raise_exceptions=False,  # Continue even if a single row fails
                )

                print(f"Batch {batch_number} evaluation complete.")

                # Append the results of the current batch to our list
                all_batch_results_df.append(result_batch.to_pandas())
            # --- End Batch Processing Loop ---

            # Combine all batch results into a single DataFrame for this file
            if not all_batch_results_df:
                print(f"No results were generated for {filename}. Skipping.")
                continue

            df = pd.concat(all_batch_results_df, ignore_index=True)
            print(f"\nAll {num_batches} batches for {filename} processed and combined.")

            # Save detailed results for this file
            output_csv_path = os.path.join(
                data_dir, f"ragas_results_{filename.replace('.json', '.csv')}"
            )
            df.to_csv(output_csv_path, index=False, encoding="utf-8-sig")
            print(f"Detailed results saved to: {output_csv_path}")

            # Store summary scores
            summary = {
                "dataset": filename.replace("ragas_eval_", "").replace(".json", "")
            }
            summary.update(df.mean(numeric_only=True).to_dict())
            all_results_summary.append(summary)

        except Exception as e:
            print(f"❌ An error occurred while processing {filename}: {e}")
            import traceback

            traceback.print_exc()

    # --- 3. Display Final Consolidated Summary ---
    if not all_results_summary:
        print("\nNo evaluations were successfully completed.")
        return

    print(f"\n{'=' * 80}")
    print("🎉 Final RAGAS Evaluation Summary")
    print(f"{'=' * 80}")

    summary_df = pd.DataFrame(all_results_summary).set_index("dataset")
    print(summary_df.round(4))

    # Save the summary dataframe
    summary_csv_path = os.path.join(data_dir, "_ragas_evaluation_summary.csv")
    summary_df.to_csv(summary_csv_path, encoding="utf-8-sig")
    print(f"\n✅ Summary report saved to: {summary_csv_path}")
    print(f"{'=' * 80}")


if __name__ == "__main__":
    main()
