CREATE OR REPLACE VIEW vs_user_data AS
SELECT o.object_id,
    o.entity_id,
    o.chinese_name,
    o.chinese_description,
    o.english_name,
    o.english_description,
    u.username,
    u.password,
    u.is_valid,
    u.status,
    u.email_verify_code,
    u.email,
    u.phone_number,
    u.address,
    u.birthday,
    u.class_id,
    u.is_send_email,
    u.last_login_datetime,
    u.login_count,
    u.login_error_count,
    o.created_at,
    o.updated_at,
    o.is_hided,
    o.is_deleted
FROM users u
    JOIN objects o ON u.user_id = o.object_id;